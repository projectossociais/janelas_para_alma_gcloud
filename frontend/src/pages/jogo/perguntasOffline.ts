export const obterPerguntasDoPatamar = (patamar: number): PerguntaOffline[] =>
  PERGUNTAS_OFFLINE_POR_PATAMAR[patamar] ?? [];

export const obterPerguntaOfflinePorId = (id: string): PerguntaOffline | undefined => {
  for (const perguntas of Object.values(PERGUNTAS_OFFLINE_POR_PATAMAR)) {
    const encontrada = perguntas.find((p) => p.id === id);
    if (encontrada) return encontrada;
  }
  return undefined;
};

/**
 * Escolhe uma pergunta aleatória do patamar que ainda não esteja em
 * `idsVistos`. Se todas já tiverem sido mostradas nesta sessão (a reserva
 * do patamar esgotou-se), em vez de rebentar ou bloquear o jogo, ignora o
 * histórico e sorteia de novo entre todas -- o chamador (`JogoCuriosidades`)
 * é responsável por então reiniciar o rastreio desse patamar.
 */
export const obterPerguntaOfflineNaoVista = (
  patamar: number,
  idsVistos: readonly string[]
): PerguntaOffline => {
  const todas = obterPerguntasDoPatamar(patamar);
  if (todas.length === 0) {
    throw new Error(`Sem perguntas offline de contingência para o patamar ${patamar}.`);
  }
  const naoVistas = todas.filter((p) => !idsVistos.includes(p.id));
  const candidatas = naoVistas.length > 0 ? naoVistas : todas;
  return candidatas[Math.floor(Math.random() * candidatas.length)];
};
