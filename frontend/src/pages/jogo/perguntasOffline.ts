/**
 * Reserva local: pelo menos 5 perguntas distintas por patamar (1 a 15),
 * embutidas no bundle. Serve quem joga sem conta (modo convidado, desde
 * 2026-09-24 -- sem sessão já não há perguntas do servidor), o site inglês, e
 * o Modo de Contingência quando a API falha (sem internet, backend em baixo).
 * Ao contrário da reserva real (na base de dados), esta fica sempre visível no
 * código-fonte do cliente -- por isso nunca dá prémios nem é tratada como
 * segura.
 *
 * As respostas certas estão distribuídas de propósito por A/B/C/D em
 * quantidades quase iguais (ver `obterPerguntaOfflineNaoVista` e o teste
 * associado) -- um jogador que reparasse num padrão (ex.: "a certa é sempre
 * a B") estaria, de facto, a explorar uma falha de design do quiz. Pela
 * mesma razão, as quatro opções de cada pergunta são deliberadamente
 * niveladas em comprimento e estrutura -- nunca deve ser possível adivinhar
 * a resposta certa só por ser a única frase desenvolvida.
 *
 * Dificuldade (revista em 2026-10, depois de jogadores se queixarem de termos
 * clínicos e de opções em frase completa): a linguagem é simples em TODOS os
 * patamares -- pergunta até 20 palavras, opções até 8 palavras e com, no
 * máximo, 3 palavras de diferença entre a mais curta e a mais longa, e
 * termos técnicos só quando a própria pergunta os explica. O que sobe de
 * patamar para patamar é a `raridade` da informação, pela curva de
 * `raridadeAlvo`. Os testes guardam as duas regras.
 */
export interface PerguntaOffline {
  id: string;
  texto_pergunta: string;
  opcao_a: string;
  opcao_b: string;
  opcao_c: string;
  opcao_d: string;
  resposta_correta: RespostaOpcaoJogo;
  explicacao: string;
  // Uma das 6 categorias oficiais. Vive só aqui (a versão inglesa herda-a
  // pelo `id`, como a resposta certa).
  categoria: CategoriaPerguntaJogo;
  // Quão rara é a informação, de 1 (toda a gente sabe) a 5 (quase ninguém
  // sabe sem ajuda). Sobe com o patamar pela curva de `raridadeAlvo`; a
  // linguagem é que nunca sobe (ver o comentário do módulo).
  raridade: Raridade;
}

export type Raridade = 1 | 2 | 3 | 4 | 5;

/**
 * Raridade média que cada patamar deve ter: 1 + 4·ln(n!)/ln(15!). O ln(n!)
 * cresce devagar no início e mais depressa no fim (como uma escada de
 * prémios), vai exactamente de 1 (patamar 1) a 5 (patamar 15) e nunca dá
 * saltos bruscos entre patamares vizinhos. Cada pergunta de um patamar fica
 * no degrau inteiro logo abaixo ou logo acima deste alvo, por isso as 15
 * perguntas sorteáveis de um patamar diferem, no máximo, um degrau entre si.
 */
export const raridadeAlvo = (patamar: number): number => {
  let lnFactorial = 0;
  let lnFactorial15 = 0;
  for (let k = 2; k <= 15; k++) {
    if (k <= patamar) lnFactorial += Math.log(k);
    lnFactorial15 += Math.log(k);
  }
  return 1 + (4 * lnFactorial) / lnFactorial15;
};

